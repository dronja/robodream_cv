"""Tests for scripts/license_report.py."""

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "license_report.py"


@pytest.fixture(scope="module")
def license_report() -> ModuleType:
    spec = importlib.util.spec_from_file_location("license_report", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class FakeMetadata:
    def __init__(self, **fields: list[str]) -> None:
        self._fields = {name.replace("_", "-"): values for name, values in fields.items()}

    def get_all(self, name: str) -> list[str] | None:
        return self._fields.get(name)


def test_parse_requirements_keeps_only_pinned(license_report: ModuleType) -> None:
    lines = [
        "# This file was autogenerated by uv",
        "numpy==2.5.4 \\",
        "    # via facehall",
        "torch==2.15.0 ; sys_platform == 'linux'",
        "torchmetrics[image]==1.9.0",
        "-e .",
        "",
    ]
    assert license_report.parse_requirements(lines) == [
        ("numpy", "2.5.4"),
        ("torch", "2.15.0"),
        ("torchmetrics", "1.9.0"),
    ]


def test_license_expression_wins(license_report: ModuleType) -> None:
    meta = FakeMetadata(
        License_Expression=["MIT"],
        License=["BSD"],
        Classifier=["License :: OSI Approved :: BSD License"],
    )
    assert license_report.license_of(meta) == "MIT"


def test_short_license_field_beats_classifiers(license_report: ModuleType) -> None:
    meta = FakeMetadata(License=["BSD-3-Clause"], Classifier=["License :: OSI Approved :: BSD"])
    assert license_report.license_of(meta) == "BSD-3-Clause"


def test_full_license_text_falls_back_to_classifiers(license_report: ModuleType) -> None:
    meta = FakeMetadata(
        License=["Copyright (c) 2020\n\nPermission is hereby granted..."],
        Classifier=["Programming Language :: Python", "License :: OSI Approved :: MIT License"],
    )
    assert license_report.license_of(meta) == "MIT License"


def test_long_license_text_without_classifiers_is_truncated(license_report: ModuleType) -> None:
    meta = FakeMetadata(License=["A" * 100 + "\nmore text"])
    result = license_report.license_of(meta)
    assert result.endswith("...")
    assert len(result) == 60


def test_missing_license_is_unknown(license_report: ModuleType) -> None:
    assert license_report.license_of(FakeMetadata(License=["UNKNOWN"])) == "UNKNOWN"
    assert license_report.license_of(FakeMetadata()) == "UNKNOWN"
