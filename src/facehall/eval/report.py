"""``docs/RESULTS.md`` from evaluation outputs, plus local comparison grids.

Input: every ``<eval root>/<protocol>/<split>/<label>/metrics.json`` written by ``facehall
eval``. The tables hold only numbers from these files. The grids show CelebA faces, so they are
written outside the repository (``outputs/``, D19).

When a scale has several protocols (degradation levels), a summary table per scale comes first:
one row per model, one column per level. Within a protocol, every model must have been scored on
the same inputs (``inputs_sha256``), or the report fails.

Real-world protocols (``kind: realworld``, no HR reference) get their own tables: FID, KID and
LR-PSNR-Y per model, then KID and LR-PSNR-Y per subset of the WIDER FACE attributes.
"""

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from PIL import Image

COLUMNS = (  # metric key, header, format, higher is better
    ("psnr_y", "PSNR-Y (dB) ↑", "{:.2f}", True),
    ("ssim_y", "SSIM-Y ↑", "{:.4f}", True),
    ("lpips", "LPIPS ↓", "{:.4f}", False),
    ("identity", "ID sim ↑", "{:.4f}", True),
)
LEVELS = ("bicubic", "light", "medium", "heavy")  # column order; other levels follow by name
REALWORLD = "realworld"
REALWORLD_SUBSETS = {
    "all": "all",
    "clear": "blur 0 (clear)",
    "normal_blur": "blur 1 (normal)",
    "heavy_blur": "blur 2 (heavy)",
    "unoccluded": "no occlusion",
    "occluded": "partial or heavy occlusion",
    "atypical_pose": "atypical pose",
    "unpadded": "no padding",
}
SUBSET_TITLES = {
    "all": "all",
    "non_blurry": "`Blurry` = 0 (D15)",
    "unpadded": "no padding (D16)",
    "male": "`Male` = 1",
    "not_male": "`Male` = 0",
    "young": "`Young` = 1",
    "not_young": "`Young` = 0",
}


def collect(root: Path) -> list[dict[str, Any]]:
    """All evaluation summaries under ``root``, each with its directory under ``"_dir"``."""
    summaries = []
    for path in sorted(root.glob("*/*/*/metrics.json")):
        summary = json.loads(path.read_text())
        summary["_dir"] = str(path.parent)
        summaries.append(summary)
    return summaries


def render(summaries: list[dict[str, Any]], *, split: str = "test") -> str:
    """Markdown tables, one section per protocol: overall metrics, then subsets."""
    lines = [
        "# Results",
        "",
        "> Generated by `scripts/make_results.py` from the `facehall eval` outputs "
        f"(`metrics.json`) on {datetime.now(UTC):%Y-%m-%d}. Do not edit by hand.",
        ">",
        "> Protocols: `configs/eval/*.yaml`. Metric definitions: `facehall.eval.metrics` and",
        "> `docs/DECISIONS.md` (D18, evaluation protocol). SR outputs are rounded to 8-bit levels",
        "> before scoring. ID sim is the cosine similarity of ArcFace embeddings of SR and HR.",
        "> Comparison grids show CelebA faces and are kept local (D19).",
        "",
        "These numbers describe how close a reconstruction is to the reference photo. A high",
        "ID similarity does not make the output a record of the real face (`CLAUDE.md` §11).",
    ]
    selected = [s for s in summaries if s["split"] == split and not s["model"].get("smoke")]
    chosen = [s for s in selected if s.get("kind") != REALWORLD]
    real = [s for s in selected if s.get("kind") == REALWORLD]
    for scale in sorted({s["scale"] for s in chosen}):
        lines += level_summary([s for s in chosen if s["scale"] == scale], scale)
    for protocol in sorted({s["protocol"] for s in real}, key=lambda p: protocol_key(real, p)):
        lines += realworld_section([s for s in real if s["protocol"] == protocol], split)
    for protocol in sorted({s["protocol"] for s in chosen}, key=lambda p: protocol_key(chosen, p)):
        rows = sorted((s for s in chosen if s["protocol"] == protocol), key=model_key)
        first = rows[0]
        count = first["subsets"]["all"]["count"]
        lines += [
            "",
            f"## {protocol} — {split} ({count:,} images, ×{first['scale']})",
            "",
            f"Level: {level(first)}. Inputs: sha256 `{inputs_digest(rows)}`.",
            "",
            "| Model | Parameters | Checkpoint | " + " | ".join(c[1] for c in COLUMNS) + " |",
            "|---|---:|---|" + "---:|" * len(COLUMNS),
        ]
        for summary in rows:
            model = summary["model"]
            checkpoint = (
                f"`{summary['label']}` (epoch {model['epoch']})" if model.get("checkpoint") else "—"
            )
            cells = [cell(summary["subsets"]["all"], key, fmt) for key, _, fmt, _ in COLUMNS]
            lines.append(
                f"| {model['name']} | {model['parameters']:,} | {checkpoint} | "
                + " | ".join(cells)
                + " |"
            )
        lines += [
            "",
            "Subsets (PSNR-Y / LPIPS / ID sim):",
            "",
            "| Subset | Images | " + " | ".join(s["model"]["name"] for s in rows) + " |",
            "|---|---:|" + "---|" * len(rows),
        ]
        for subset, title in SUBSET_TITLES.items():
            stats = first["subsets"].get(subset)
            if stats is None:
                continue
            cells = [compact(s["subsets"][subset]) for s in rows]
            lines.append(f"| {title} | {stats['count']:,} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def realworld_section(rows: list[dict[str, Any]], split: str) -> list[str]:
    """FID, KID and LR-PSNR-Y per model, then KID and LR-PSNR-Y per subset."""
    rows = sorted(rows, key=model_key)
    first = rows[0]
    count = first["subsets"]["all"]["count"]
    reference = first.get("reference") or {}
    lines = [
        "",
        f"## {first['protocol']} — real-world faces, no reference ({split}, {count:,} faces, "
        f"×{first['scale']})",
        "",
        f"Inputs: sha256 `{inputs_digest(rows)}`. FID and KID compare the outputs with "
        f"{reference.get('samples', 0):,} real HR faces (CelebA `{reference.get('split', '?')}` "
        "crops); lower is closer. They measure how real the outputs look as a set, not whether "
        "they show the right person. LR-PSNR-Y compares the downscaled output with the input; "
        "plain upsampling scores high on it.",
        "",
        "| Model | Parameters | Checkpoint | FID ↓ | KID ×10³ ↓ | LR-PSNR-Y (dB) ↑ |",
        "|---|---:|---|---:|---:|---:|",
    ]
    for summary in rows:
        model = summary["model"]
        checkpoint = (
            f"`{summary['label']}` (epoch {model['epoch']})" if model.get("checkpoint") else "—"
        )
        stats = summary["subsets"]["all"]
        fid = f"{stats['fid']:.2f}" if stats.get("fid") is not None else "—"
        lines.append(
            f"| {model['name']} | {model['parameters']:,} | {checkpoint} | {fid} | "
            f"{kid_cell(stats)} | {cell(stats, 'lr_psnr_y', '{:.2f}')} |"
        )
    lines += [
        "",
        "Subsets (KID ×10³ / LR-PSNR-Y; KID only for subsets of enough faces):",
        "",
        "| Subset | Faces | " + " | ".join(s["model"]["name"] for s in rows) + " |",
        "|---|---:|" + "---|" * len(rows),
    ]
    for subset, title in REALWORLD_SUBSETS.items():
        stats = first["subsets"].get(subset)
        if stats is None:
            continue
        cells = [
            kid_cell(s["subsets"][subset])
            + " / "
            + cell(s["subsets"][subset], "lr_psnr_y", "{:.2f}")
            for s in rows
        ]
        lines.append(f"| {title} | {stats['count']:,} | " + " | ".join(cells) + " |")
    return lines


def kid_cell(stats: dict[str, Any]) -> str:
    value = stats.get("kid")
    if not value:
        return "—"
    return f"{value['mean'] * 1e3:.2f} ± {value['std'] * 1e3:.2f}"


def level(summary: dict[str, Any]) -> str:
    return str(summary.get("level") or summary["protocol"])


def level_rank(name: str) -> tuple[int, str]:
    return (LEVELS.index(name), "") if name in LEVELS else (len(LEVELS), name)


def protocol_key(summaries: list[dict[str, Any]], protocol: str) -> tuple[int, int, str]:
    first = next(s for s in summaries if s["protocol"] == protocol)
    rank, name = level_rank(level(first))
    return first["scale"], rank, name + protocol


def model_key(summary: dict[str, Any]) -> tuple[bool, str, str]:
    return summary["model"]["parameters"] > 0, summary["model"]["name"], summary["label"]


def inputs_digest(rows: list[dict[str, Any]]) -> str:
    """The shared inputs digest of one protocol's results; "unknown" for older results."""
    digests = {str(s["inputs_sha256"]) for s in rows if s.get("inputs_sha256")}
    if len(digests) > 1:
        labels = ", ".join(f"{s['label']}: {s.get('inputs_sha256')}" for s in rows)
        raise ValueError(
            f"protocol {rows[0]['protocol']}: models were scored on different inputs ({labels}); "
            "re-evaluate them on the frozen inputs"
        )
    return digests.pop() if digests else "unknown"


def level_summary(summaries: list[dict[str, Any]], scale: int) -> list[str]:
    """One row per model, one column per degradation level (PSNR-Y / LPIPS / ID sim)."""
    levels = sorted({level(s) for s in summaries}, key=level_rank)
    if len(levels) < 2:
        return []
    by_label: dict[str, dict[str, dict[str, Any]]] = {}
    for summary in sorted(summaries, key=model_key):
        by_label.setdefault(summary["label"], {})[level(summary)] = summary
    lines = [
        "",
        f"## Summary by degradation level — ×{scale}",
        "",
        "PSNR-Y / LPIPS / ID sim on all images of each protocol.",
        "",
        "| Model | " + " | ".join(levels) + " |",
        "|---|" + "---|" * len(levels),
    ]
    for label, row in by_label.items():
        cells = [compact(row[name]["subsets"]["all"]) if name in row else "—" for name in levels]
        lines.append(f"| `{label}` | " + " | ".join(cells) + " |")
    return lines


def cell(stats: dict[str, Any], key: str, fmt: str) -> str:
    value = stats.get(key)
    return fmt.format(value["mean"]) if value else "—"


def compact(stats: dict[str, Any]) -> str:
    parts = [cell(stats, key, fmt) for key, fmt in (("psnr_y", "{:.2f}"), ("lpips", "{:.3f}"))]
    return " / ".join([*parts, cell(stats, "identity", "{:.3f}")])


def comparison_grid(summaries: list[dict[str, Any]], protocol: str, split: str) -> Image.Image:
    """Rows: grid samples. Columns: LR (nearest upscale), each model's SR, HR (if there is one)."""
    rows = sorted(
        (
            s
            for s in summaries
            if s["protocol"] == protocol and s["split"] == split and not s["model"].get("smoke")
        ),
        key=model_key,
    )
    reference = Path(rows[0]["_dir"]).parent / "reference"
    names = sorted(p.name for p in (reference / "lr").glob("*.png"))
    samples = [Path(s["_dir"]) / "samples" for s in rows]
    columns = [
        reference / "lr",
        *samples,
        *([reference / "hr"] if (reference / "hr").is_dir() else []),
    ]
    size = Image.open(samples[0] / names[0]).size[0]
    grid = Image.new("RGB", (size * len(columns), size * len(names)), "white")
    for r, name in enumerate(names):
        for c, folder in enumerate(columns):
            path = folder / name
            if path.is_file():
                image = Image.open(path).convert("RGB")
                image = image.resize((size, size), Image.Resampling.NEAREST)
                grid.paste(image, (c * size, r * size))
    return grid
